HostKey chatToHost(uint8_t kc, uint8_t layers) {
  HostKey none = { HK_NONE, 0 };
  switch (kc) {
    case CHAT_KEY_SPACE: {
      HostKey k = { HK_ASCII, ' ' };
      return k;
    }
    case CHAT_KEY_ENTER: {
      HostKey k = { HK_ENTER, 0 };
      return k;
    }
    case CHAT_KEY_BACKSPACE: {
      HostKey k = { HK_BACKSPACE, 0 };
      return k;
    }
    case CHAT_KEY_LEFT: {
      HostKey k = { HK_LEFT, 0 };
      return k;
    }
    case CHAT_KEY_RIGHT: {
      HostKey k = { HK_RIGHT, 0 };
      return k;
    }
  }
  if (kc < 0x11 || kc > 0x88)
    return none;

  uint8_t off = kc - 0x11;
  uint8_t idx = ((off & 0x70) >> 1) | (off & 0x07);

  uint16_t c = 0;
  if (layers & CHAT_MOD_SHIFT)
    c = kShiftUS[idx];
  else if (layers & CHAT_MOD_GREEN)
    c = kGreen[idx];
  else if (layers & CHAT_MOD_ORANGE)
    c = kOrange[idx];
  else
    c = kBaseUS[idx];

  if (c == 0) {
    HostKey k = { HK_NONE, 0 };
    return k;
  }
  HostKey k = { HK_ASCII, c };
  return k;
}
